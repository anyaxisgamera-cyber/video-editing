#!/usr/bin/env python3
"""Synthetic-media test for scripts/production.py (no network, no Remotion render).

Covers: init (videos × languages × formats × resolutions), register-add with measured facts, audit (licence,
checksum and missing-asset failures, credits), per-language timing maps from measured narration (different
durations per language, contiguous frame grid, captions, SRT, ducking keyframes, target fitting), Remotion props for
9:16 and 16:9, 4K feasibility, the audio mastering loop, and deliverable status (validated / missing / stale).
"""

from __future__ import annotations

import importlib.util
import json
import subprocess
import sys
import tempfile
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parent.parent
PRODUCTION = SKILL_DIR / "scripts" / "production.py"
WORKBENCH = SKILL_DIR / "scripts" / "video_workbench.py"


def run(cmd: list, ok: bool = True) -> subprocess.CompletedProcess:
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True)
    if ok and r.returncode != 0:
        raise AssertionError(f"command failed ({r.returncode}): {' '.join(map(str, cmd))}\n{r.stdout}\n{r.stderr}")
    return r


def ff(*args) -> None:
    run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *args])


def tone(path: Path, seconds: float, lead: float, tail: float, freq: int = 220) -> None:
    """A narration stand-in: silence, an amplitude-modulated tone (speech-like envelope), silence."""
    ff("-f", "lavfi", "-i", f"anullsrc=r=48000:cl=mono:d={lead}",
       "-f", "lavfi", "-i", f"sine=frequency={freq}:sample_rate=48000:duration={seconds}",
       "-f", "lavfi", "-i", f"anullsrc=r=48000:cl=mono:d={tail}",
       "-filter_complex", "[1]volume='0.5+0.4*sin(2*PI*4*t)':eval=frame[s];[0][s][2]concat=n=3:v=0:a=1[a]",
       "-map", "[a]", str(path))


def main() -> None:
    with tempfile.TemporaryDirectory(prefix="production-test-") as raw:
        tmp = Path(raw)
        prod = tmp / "prod"
        run([sys.executable, PRODUCTION, "init", prod, "--videos", "1", "--languages", "en,te", "--durations", "12",
             "--formats", "9:16,16:9", "--resolutions", "1080,2160", "--commercial"])
        doc = json.loads((prod / "production.json").read_text())
        assert len(doc["deliverables"]) == 8, doc["deliverables"]
        assert doc["languages"]["te"]["max_chars"] < doc["languages"]["en"]["max_chars"]

        # synthetic assets (registered as generated, with measured facts)
        a = prod / "assets"
        ff("-f", "lavfi", "-i", "testsrc2=size=640x360:rate=30:duration=8", "-pix_fmt", "yuv420p", str(a / "a01.mp4"))
        ff("-f", "lavfi", "-i", "mandelbrot=size=640x360:rate=30", "-t", "8", "-pix_fmt", "yuv420p", str(a / "a02.mp4"))
        ff("-f", "lavfi", "-i", "testsrc=size=360x640", "-frames:v", "1", str(a / "a03.png"))
        ff("-f", "lavfi", "-i", "sine=frequency=110:sample_rate=48000:duration=20", "-ac", "2", str(a / "m01.wav"))
        ff("-f", "lavfi", "-i", "anoisesrc=d=0.6:c=pink:a=0.3:r=48000", str(a / "x01.wav"))
        for aid, kind, lic, com in [("a01", "video", "CC0 1.0", "yes"), ("a02", "video", "CC BY-NC 4.0", "no"),
                                    ("a03", "image", "CC0 1.0", "yes"), ("m01", "music", "CC0 1.0", "yes"),
                                    ("x01", "sfx", "CC0 1.0", "yes")]:
            ext = {"video": "mp4", "image": "png"}.get(kind, "wav")
            run([sys.executable, PRODUCTION, "register-add", prod, "--id", aid, "--kind", kind, "--file", f"assets/{aid}.{ext}",
                 "--title", f"synthetic {aid}", "--source-url", "generated", "--licence", lic, "--commercial-use", com,
                 "--evidence", "generated by the test with ffmpeg lavfi"])
        reg = json.loads((prod / "research" / "source-register.json").read_text())
        facts = {x["id"]: x for x in reg["assets"]}
        assert facts["a01"]["probe"]["width"] == 640 and abs(facts["a01"]["probe"]["duration"] - 8) < 0.1
        assert facts["a03"]["probe"].get("still") is True
        assert len(facts["a01"]["sha256"]) == 64
        # registering a file that does not exist must fail
        r = run([sys.executable, PRODUCTION, "register-add", prod, "--id", "zz", "--kind", "video", "--file", "assets/nope.mp4",
                 "--title", "x", "--source-url", "https://example.invalid/x", "--licence", "x"], ok=False)
        assert r.returncode != 0 and "does not exist" in (r.stdout + r.stderr)

        scenes = {
            "video": "v01", "fps": 30, "lead_in_seconds": 0.5, "gap_seconds": 0.35, "tail_seconds": 1.0,
            "scenes": [
                {"id": "s01", "narration": {"en": "Every journey starts with a single step.", "te": "ప్రతి ప్రయాణం ఒక్క అడుగుతోనే మొదలవుతుంది."},
                 "on_screen": {"en": "Begin", "te": "ప్రారంభం"},
                 "visual": {"asset": "a01", "in": 1.0, "fit": "cover", "focus": [0.5, 0.5], "move": {"type": "push_in", "amount": 0.05}},
                 "transition_in": {"type": "cut", "seconds": 0}, "min_seconds": 2.0,
                 "sfx": [{"asset": "x01", "at": "start", "offset_seconds": -0.1, "volume": 0.4}]},
                {"id": "s02", "narration": {"en": "Keep walking, even when the road is long.", "te": "దారి సుదీర్ఘంగా ఉన్నా నడుస్తూనే ఉండండి."},
                 "visual": {"asset": "a02", "in": 0.0, "fit": "cover", "focus": [0.4, 0.5], "move": {"type": "pan_right", "amount": 0.08}},
                 "transition_in": {"type": "fade", "seconds": 0.4}, "min_seconds": 2.0},
                {"id": "s03", "narration": {"en": "", "te": ""}, "on_screen": {"en": "Thank you", "te": "ధన్యవాదాలు"},
                 "visual": {"asset": "a03", "fit": "cover", "focus": [0.5, 0.5], "move": {"type": "static", "amount": 0}},
                 "transition_in": {"type": "fade_from_black", "seconds": 0.5}, "min_seconds": 2.0},
            ],
            "music": {"asset": "m01", "volume": 0.3, "duck_to": 0.1, "fade_out_seconds": 1.5},
        }
        (prod / "plan" / "v01" / "scenes.json").write_text(json.dumps(scenes, ensure_ascii=False))

        # audit fails: commercial production uses a non-commercial asset (a02)
        r = run([sys.executable, PRODUCTION, "audit", prod], ok=False)
        assert r.returncode == 1 and "does not allow commercial use" in r.stdout, r.stdout
        scenes["scenes"][1]["visual"]["asset"] = "a01"
        scenes["scenes"][1]["visual"]["in"] = 3.5
        (prod / "plan" / "v01" / "scenes.json").write_text(json.dumps(scenes, ensure_ascii=False))
        run([sys.executable, PRODUCTION, "audit", prod, "--credits", "reports/credits.md"])
        assert "synthetic a01" in (prod / "reports" / "credits.md").read_text()

        # timing needs narration: missing files are errors, never guessed
        r = run([sys.executable, PRODUCTION, "timing", prod, "--video", "v01", "--language", "en"], ok=False)
        assert r.returncode == 1 and "is missing" in r.stdout, r.stdout + r.stderr
        n = prod / "narration" / "v01"
        tone(n / "en" / "s01.wav", 2.4, 0.2, 0.3)
        tone(n / "en" / "s02.wav", 2.2, 0.15, 0.25)
        tone(n / "te" / "s01.wav", 3.1, 0.2, 0.3, 260)  # Telugu narration is longer: timing must differ
        tone(n / "te" / "s02.wav", 2.9, 0.15, 0.25, 260)
        for lang in ("en", "te"):  # narration is an asset like any other: registered with its licence
            for sid in ("s01", "s02"):
                run([sys.executable, PRODUCTION, "register-add", prod, "--id", f"vo-v01-{lang}-{sid}", "--kind", "voice",
                     "--file", f"narration/v01/{lang}/{sid}.wav", "--title", f"test narration {lang} {sid}",
                     "--source-url", "generated", "--licence", "CC0 1.0", "--commercial-use", "yes",
                     "--evidence", "synthetic tone generated by the test", "--status", "used"])
        # word timestamps for en/s01 matching the script words exactly
        words = "Every journey starts with a single step.".split()
        (n / "en" / "s01.words.json").write_text(json.dumps({"segments": [{"words": [
            {"word": w, "start": 0.2 + 0.3 * i, "end": 0.2 + 0.3 * i + 0.25} for i, w in enumerate(words)]}]}))
        run([sys.executable, PRODUCTION, "timing", prod, "--video", "v01", "--language", "en"])
        run([sys.executable, PRODUCTION, "timing", prod, "--video", "v01", "--language", "te"])
        en = json.loads((prod / "timing" / "v01" / "en.timing.json").read_text())
        te = json.loads((prod / "timing" / "v01" / "te.timing.json").read_text())
        assert te["durationInFrames"] > en["durationInFrames"], (te["durationInFrames"], en["durationInFrames"])
        for tm in (en, te):
            sc = tm["scenes"]
            assert sc[0]["cut"] == 0 and sc[-1]["end"] == tm["durationInFrames"]
            assert all(x["end"] == y["cut"] for x, y in zip(sc, sc[1:])), "cut points must be contiguous"
            assert sc[1]["from"] < sc[1]["cut"], "a crossfade starts the incoming shot early"
            assert sc[2]["from"] == sc[2]["cut"], "fade_from_black does not overlap"
            assert tm["narration"][0]["from"] == round(0.5 * 30)
            keys = tm["music"]["keyframes"]
            assert all(b[0] > a_[0] for a_, b in zip(keys, keys[1:])), "music keyframes must be strictly increasing"
            assert min(k[1] for k in keys[2:-2]) <= 0.1 + 1e-6, "music must duck under narration"
            assert tm["captions"] and all(c["endMs"] > c["startMs"] for c in tm["captions"])
            assert tm["captions"][1]["text"].startswith(" "), "Caption tokens after the first carry a leading space"
            assert (prod / "captions" / "v01" / f"{tm['language']}.srt").read_text().startswith("1\n")
            assert tm["fit"]["delta_seconds"] is not None
        assert "word-timestamps" in en["caption_method"] and any(m.startswith("proportional") for m in en["caption_method"])
        first = [c for c in en["captions"] if c["scene"] == "s01"]
        assert first[1]["startMs"] == round((0.5 + 0.5) * 1000), first[1]  # 0.5 s lead-in + word 2 at 0.5 s
        # --fit gaps moves the total towards the 12 s target without touching narration
        before = abs(te["seconds"] - 12)
        run([sys.executable, PRODUCTION, "timing", prod, "--video", "v01", "--language", "te", "--fit", "gaps"])
        te_fit = json.loads((prod / "timing" / "v01" / "te.timing.json").read_text())
        assert abs(te_fit["seconds"] - 12) < before, (te_fit["seconds"], te["seconds"])
        assert [x["seconds"] for x in te_fit["narration"]] == [x["seconds"] for x in te["narration"]]

        # props for both formats
        motion = tmp / "motion"
        (motion / "src" / "script-video").mkdir(parents=True)
        for fmt, size in (("9:16", (1080, 1920)), ("16:9", (1920, 1080))):
            run([sys.executable, PRODUCTION, "props", prod, "--video", "v01", "--language", "te", "--format", fmt,
                 "--resolution", "1080", "--motion-project", motion])
            p = json.loads((motion / "props" / f"v01-te-{fmt.replace(':', 'x')}-1080.json").read_text())
            assert (p["canvas"]["width"], p["canvas"]["height"]) == size
            assert p["canvas"]["durationInFrames"] == te_fit["durationInFrames"]
            assert (motion / "public" / p["scenes"][0]["media"]["src"]).exists()
            assert p["scenes"][2]["media"]["kind"] == "image"
            assert p["narration"] and (motion / "public" / p["narration"][0]["src"]).exists()
            assert {t["sceneId"] for t in p["captionTracks"]} == {"s01", "s02"}
        p4 = json.loads(run([sys.executable, PRODUCTION, "props", prod, "--video", "v01", "--language", "en", "--format", "16:9",
                             "--resolution", "2160", "--motion-project", motion]).stdout)
        assert (p4["width"], p4["height"]) == (3840, 2160)

        spec = importlib.util.spec_from_file_location("production", PRODUCTION)
        mod = importlib.util.module_from_spec(spec)
        sys.path.insert(0, str(PRODUCTION.parent))
        spec.loader.exec_module(mod)

        # per-format framing: letterbox the vertical cut, punch in on the landscape one; both counted in the upscale
        scenes["scenes"][0]["visual"].update({"fit": {"9:16": "contain", "16:9": "cover"}, "zoom": {"16:9": 1.5}})
        (prod / "plan" / "v01" / "scenes.json").write_text(json.dumps(scenes, ensure_ascii=False))
        run([sys.executable, PRODUCTION, "timing", prod, "--video", "v01", "--language", "en"])
        for fmt, fit, zoom in (("9:16", "contain", 1.0), ("16:9", "cover", 1.5)):
            run([sys.executable, PRODUCTION, "props", prod, "--video", "v01", "--language", "en", "--format", fmt,
                 "--resolution", "1080", "--motion-project", motion])
            m0 = json.loads((motion / "props" / f"v01-en-{fmt.replace(':', 'x')}-1080.json").read_text())["scenes"][0]["media"]
            assert (m0["fit"], m0["zoom"]) == (fit, zoom), m0
        rc = {f: mod.resolution_class(prod, mod.load_prod(prod), "v01", f, 1080)["scenes"][0]["upscale"] for f in ("9:16", "16:9")}
        assert abs(rc["16:9"] - 3.0 * 1.5 * 1.05) < 0.01 and abs(rc["9:16"] - 1.6875 * 1.05) < 0.01, rc
        scenes["scenes"][0]["visual"]["zoom"] = 0.8
        (prod / "plan" / "v01" / "scenes.json").write_text(json.dumps(scenes, ensure_ascii=False))
        r = run([sys.executable, PRODUCTION, "timing", prod, "--video", "v01", "--language", "en"], ok=False)
        assert r.returncode == 1 and "zoom" in r.stdout, r.stdout
        scenes["scenes"][0]["visual"].pop("zoom")
        scenes["scenes"][0]["visual"]["fit"] = "cover"

        # licence gate: a render that would use a non-commercial asset is blocked before anything is rendered
        scenes["scenes"][1]["visual"]["asset"] = "a02"
        (prod / "plan" / "v01" / "scenes.json").write_text(json.dumps(scenes, ensure_ascii=False))
        r = run([sys.executable, PRODUCTION, "render", prod, "--video", "v01", "--language", "en", "--format", "16:9",
                 "--resolution", "1080", "--motion-project", motion], ok=False)
        assert r.returncode == 3 and "a02" in (r.stdout + r.stderr), (r.returncode, r.stdout, r.stderr)
        blocked = [x for x in json.loads((prod / "production.json").read_text())["deliverables"] if x.get("status") == "blocked"]
        assert len(blocked) == 1 and blocked[0]["blockers"], blocked
        scenes["scenes"][1]["visual"]["asset"] = "a01"
        (prod / "plan" / "v01" / "scenes.json").write_text(json.dumps(scenes, ensure_ascii=False))
        r = run([sys.executable, PRODUCTION, "status", prod], ok=False)
        assert "blocked" not in r.stdout, "status re-evaluates blockers instead of repeating a resolved one: " + r.stdout
        run([sys.executable, PRODUCTION, "timing", prod, "--video", "v01", "--language", "en"])
        run([sys.executable, PRODUCTION, "timing", prod, "--video", "v01", "--language", "te", "--fit", "gaps"])

        # QC failure detection on encoded files: unexpected black, missing audio, captions that differ from the script
        import qc
        tm = json.loads((prod / "timing" / "v01" / "en.timing.json").read_text())
        secs = tm["durationInFrames"] / 30
        bad = tmp / "bad.mp4"
        ff("-f", "lavfi", "-i", f"testsrc2=size=320x180:rate=30:duration={secs:.3f}", "-vf",
           f"drawbox=enable='between(t,{secs / 2 - 0.6:.2f},{secs / 2 + 0.6:.2f})':color=black:t=fill",
           "-c:v", "libx264", "-pix_fmt", "yuv420p", str(bad))
        srt = prod / "captions" / "v01" / "en.srt"
        wrong = tmp / "wrong.srt"
        wrong.write_text(srt.read_text().replace("journey", "journal"))
        rep = qc.run_qc(bad, tm, wrong, None, [], 30, None)
        assert not rep["checks"]["audio_present"]["passed"], rep["checks"]["audio_present"]
        assert rep["checks"]["no_unexpected_black"]["detail"]["unexpected"], rep["checks"]["no_unexpected_black"]
        assert "journal" in rep["checks"]["captions_match_script"]["detail"] and not rep["passed"]
        assert qc.run_qc(bad, tm, srt, None, [], 30, None)["checks"]["captions_match_script"]["passed"]

        # narration drift: a mix with the narration 120 ms late is measured as such (tolerance ±10 ms)
        n0 = tm["narration"][0]
        mix = tmp / "drift.wav"
        delay = n0["from"] / 30 + 0.120
        ff("-i", str(prod / n0["path"]), "-af", f"adelay={int(delay * 1000)}:all=1,apad=pad_dur=1", "-ar", "48000", str(mix))
        tm1 = dict(tm, narration=[n0])
        off = mod.narration_offsets(prod, tm1, mix)
        assert off is None or abs(off[n0["scene"]] - 120) <= 2, off  # numpy missing → not measured, never "passed"

        # 4K feasibility from 640x360 sources: upscaled, never "native"
        out = run([sys.executable, PRODUCTION, "feasibility", prod]).stdout
        assert "upscaled" in out, out
        feas = json.loads((prod / "reports" / "feasibility.json").read_text())
        assert all(r["verdict"].startswith("upscaled") for r in feas["rows"])

        # mastering loop (imported) on a quiet synthetic programme
        quiet = tmp / "quiet.mp4"
        ff("-f", "lavfi", "-i", "testsrc2=size=320x180:rate=30:duration=4", "-f", "lavfi", "-i",
           "sine=frequency=330:sample_rate=48000:duration=4", "-filter_complex", "[1]volume=0.05[a]", "-map", "0:v", "-map", "[a]",
           "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest", str(quiet))
        mastered = tmp / "mastered.mp4"
        m = mod.master_audio(quiet, mastered, {"I": -16, "TP": -1.5})
        assert m["compliant"], m
        assert abs(mod.loudness(mastered)["I"] + 16) <= 0.5
        # a picture tagged only with a BT.709 matrix (what Remotion writes) leaves mastering fully tagged, pixels unchanged
        part = tmp / "matrix-only.mp4"
        ff("-f", "lavfi", "-i", "testsrc2=size=320x180:rate=30:duration=2", "-f", "lavfi", "-i",
           "sine=frequency=330:sample_rate=48000:duration=2", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-colorspace", "bt709",
           "-c:a", "aac", "-shortest", str(part))
        assert mod.colour_tag_args(part) and not mod.colour_tag_args(quiet), "only a BT.709-matrix H.264 stream is retagged"
        tagged = tmp / "tagged.mp4"
        assert mod.master_audio(part, tagged, {"I": -16, "TP": -1.5})["colour_tags"] != "unchanged"
        tags = run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
                    "stream=color_space,color_transfer,color_primaries", "-of", "csv=p=0", tagged]).stdout.strip()
        assert tags == "bt709,bt709,bt709", tags
        md5 = [run(["ffmpeg", "-v", "error", "-i", f, "-map", "0:v", "-f", "md5", "-"]).stdout for f in (part, tagged)]
        assert md5[0] == md5[1], "tagging must not change a single pixel"

        # status: one validated deliverable, the rest missing; then a changed file becomes stale
        d = prod / "deliverables" / "v01" / "en" / "v01-en-16x9-1080.mp4"
        ff("-f", "lavfi", "-i", "testsrc2=size=1920x1080:rate=30:duration=2", "-f", "lavfi", "-i",
           "sine=frequency=440:sample_rate=48000:duration=2", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac",
           "-shortest", str(d))
        run([sys.executable, WORKBENCH, "validate", d, "--report", d.with_suffix(".validation.json"), "--width", "1920",
             "--height", "1080", "--audio-rate", "48000"])
        # the synthetic sources need upscaling even at 1080p: not delivered until the user accepts the upscale
        r = run([sys.executable, PRODUCTION, "status", prod], ok=False)
        assert r.returncode == 1 and "0/8 deliverables validated" in r.stdout, r.stdout
        assert "upscaled  deliverables/v01/en/v01-en-16x9-1080.mp4" in r.stdout and "needs the user's acceptance" in r.stdout
        doc = json.loads((prod / "production.json").read_text())
        for dl in doc["deliverables"]:
            if dl["path"].endswith("v01-en-16x9-1080.mp4"):
                dl["upscale_accepted"] = True
        (prod / "production.json").write_text(json.dumps(doc, ensure_ascii=False, indent=2))
        r = run([sys.executable, PRODUCTION, "status", prod], ok=False)
        assert r.returncode == 1 and "1/8 deliverables validated" in r.stdout, r.stdout
        assert "  validated  deliverables/v01/en/v01-en-16x9-1080.mp4" in r.stdout
        with d.open("ab") as fh:
            fh.write(b"\0")
        r = run([sys.executable, PRODUCTION, "status", prod], ok=False)
        assert "stale" in r.stdout and "0/8 deliverables validated" in r.stdout, r.stdout
        print("production tooling test passed")


if __name__ == "__main__":
    main()
